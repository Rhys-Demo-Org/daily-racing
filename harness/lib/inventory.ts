// Inputs for reviewer R3 (duplication, plans/full-pipeline.md step 7): an inventory of everything
// `src/` exports, and a simple clone report: runs of CLONE_LINES normalised lines that appear in
// more than one place, at least one of them in a file the branch changed. Regex-level, no parser:
// it points the reviewer at candidates, the reviewer judges them.

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

export const CLONE_LINES = 6;
const SOURCE = /\.(ts|tsx|css)$/;

/** Every source file under `root/dir`, repo-relative, sorted. */
export function sourceFiles(root: string, dir = 'src'): string[] {
  const out: string[] = [];
  const walk = (p: string): void => {
    const st = statSync(p, { throwIfNoEntry: false });
    if (st?.isDirectory()) for (const n of readdirSync(p)) walk(join(p, n));
    else if (st?.isFile() && SOURCE.test(p)) out.push(relative(root, p));
  };
  walk(join(root, dir));
  return out.sort();
}

const EXPORT = /^export\s+(?:default\s+)?(?:declare\s+)?(?:async\s+)?(function\*?|const|let|class|type|interface)\s+([A-Za-z_$][\w$]*)/;

/** `- name (kind, line n)` per export, grouped by file. */
export function exportInventory(root: string, files: readonly string[]): string {
  const lines = ['# Exported functions, components and types in src/', '', 'Generated by the harness. Reuse these before adding a parallel copy.', ''];
  for (const f of files.filter((x) => x.endsWith('.ts') || x.endsWith('.tsx'))) {
    const found = readFileSync(join(root, f), 'utf8').split('\n').flatMap((l, i) => {
      const m = EXPORT.exec(l);
      return m ? [`${m[2]} (${m[1]!.replace('*', '')}, line ${i + 1})`] : [];
    });
    if (found.length) lines.push(`## ${f}`, '', ...found.map((x) => `- ${x}`), '');
  }
  return lines.join('\n');
}

/** A line as the clone finder compares it: no comments or whitespace, nothing trivial. */
function norm(line: string): string {
  const t = line.replace(/\/\/.*$/, '').replace(/\/\*.*?\*\//g, '').replace(/\s+/g, '');
  return /^[{}()[\];,]*$/.test(t) || /^(import|export\{|\*|\/\*)/.test(t) ? '' : t;
}

type Site = { file: string; line: number };

/**
 * Runs of CLONE_LINES consecutive non-trivial lines found in two or more places, where at least
 * one place is in `changed`. Overlapping windows of one clone are merged into a single entry.
 */
export function cloneReport(root: string, files: readonly string[], changed: readonly string[]): string {
  const windows = new Map<string, Site[]>();
  for (const f of files) {
    const rows = readFileSync(join(root, f), 'utf8').split('\n').map((l, i) => ({ t: norm(l), line: i + 1 })).filter((r) => r.t !== '');
    for (let i = 0; i + CLONE_LINES <= rows.length; i++) {
      const key = rows.slice(i, i + CLONE_LINES).map((r) => r.t).join('\n');
      const sites = windows.get(key) ?? [];
      sites.push({ file: f, line: rows[i]!.line });
      windows.set(key, sites);
    }
  }
  const touched = new Set(changed);
  const seen = new Set<string>();
  const clones: Site[][] = [];
  for (const sites of windows.values()) {
    if (sites.length < 2 || !sites.some((s) => touched.has(s.file))) continue;
    // Merge with an earlier clone that has the same files a few lines back (overlapping windows).
    const near = sites.map((s) => `${s.file}:${Math.floor(s.line / (CLONE_LINES * 2))}`).join('|');
    if (seen.has(near)) continue;
    seen.add(near);
    clones.push(sites);
  }
  const lines = ['# Clone report', '', `Runs of ${CLONE_LINES}+ identical lines (ignoring whitespace and comments) that occur more than once, at least once in a file this branch changed.`, ''];
  if (!clones.length) lines.push('No clones found.');
  for (const c of clones.slice(0, 60)) lines.push(`- ${c.map((s) => `\`${s.file}:${s.line}\``).join(' = ')}`);
  if (clones.length > 60) lines.push(`- … ${clones.length - 60} more`);
  return lines.join('\n') + '\n';
}
